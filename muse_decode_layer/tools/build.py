"""Build a standalone submission from decode/ without importing GPU packages."""

import argparse
import ast
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PRESETS = ("control", "full_fa3", "full_fa3_m16", "full_fa3_m16_finalize", "full_fa3_m8_finalize", "single_nvfp4")
SOURCES = (
    "decode/spec.py",
    "decode/config.py",
    "decode/projections.py",
    "decode/boundaries.py",
    "decode/nvfp4_gemv.py",
    "decode/experts.py",
    "decode/attention.py",
    "decode/runtime.py",
)


def build_source(preset="full_fa3_m16_finalize"):
    if preset not in PRESETS:
        raise ValueError(f"unknown preset: {preset}")
    chunks = ["# okc: problem=muse_decode_layer\n",
              "# Generated by python -m tools.build; edit decode/ sources.\n"]
    imports = set()
    definitions = set()
    for name in SOURCES:
        source = (ROOT / name).read_text()
        lines = source.splitlines(keepends=True)
        chunks.append(f"\n# Source: {name}\n")
        for node in ast.parse(source).body:
            if isinstance(node, ast.ImportFrom) and node.level:
                continue
            if (isinstance(node, ast.Expr) and isinstance(node.value, ast.Constant)
                    and isinstance(node.value.value, str)):
                continue
            if isinstance(node, (ast.Import, ast.ImportFrom)):
                key = ast.dump(node)
                if key in imports:
                    continue
                imports.add(key)
            if isinstance(node, (ast.FunctionDef, ast.ClassDef)):
                if node.name in definitions:
                    raise ValueError(f"duplicate definition: {node.name}")
                definitions.add(node.name)
            start = min([node.lineno] + [d.lineno for d in getattr(node, "decorator_list", [])])
            block = "".join(lines[start - 1:node.end_lineno]).rstrip()
            if (isinstance(node, ast.Assign)
                    and any(isinstance(target, ast.Name) and target.id == "ATTENTION_BACKEND"
                            for target in node.targets)):
                backend = "control" if preset == "control" else "full_fa3"
                block = f"ATTENTION_BACKEND = {backend!r}"
            if (preset in ("full_fa3_m16", "full_fa3_m16_finalize", "single_nvfp4") and isinstance(node, ast.Assign)
                    and any(isinstance(target, ast.Name) and target.id == "BLOCK_SIZE_M_CANDIDATES"
                            for target in node.targets)):
                # Same expert implementation; cap only the existing selector.
                block = "BLOCK_SIZE_M_CANDIDATES = (8, 16)"
            if (preset == "full_fa3_m8_finalize" and isinstance(node, ast.Assign)
                    and any(isinstance(target, ast.Name) and target.id == "BLOCK_SIZE_M_CANDIDATES"
                            for target in node.targets)):
                block = "BLOCK_SIZE_M_CANDIDATES = (8,)"
            if (isinstance(node, ast.Assign)
                    and any(isinstance(target, ast.Name) and target.id == "SMALL_EXPERT_FINALIZE"
                            for target in node.targets)):
                block = f"SMALL_EXPERT_FINALIZE = {(preset.endswith('_finalize') or preset == 'single_nvfp4')!r}"
            if (isinstance(node, ast.Assign)
                    and any(isinstance(target, ast.Name) and target.id == "DIRECT_SINGLE_EXPERTS"
                            for target in node.targets)):
                block = f"DIRECT_SINGLE_EXPERTS = {preset == 'single_nvfp4'!r}"
            chunks.append(block + "\n\n")
    source = "".join(chunks).rstrip() + "\n"
    compile(source, "<standalone submission>", "exec")
    return source


def source_manifest(source):
    tree = ast.parse(source)
    backend = next(ast.literal_eval(node.value) for node in tree.body
                   if isinstance(node, ast.Assign) and any(
                       isinstance(target, ast.Name) and target.id == "ATTENTION_BACKEND"
                       for target in node.targets))
    blocks = next(ast.literal_eval(node.value) for node in tree.body
                  if isinstance(node, ast.Assign) and any(
                      isinstance(target, ast.Name) and target.id == "BLOCK_SIZE_M_CANDIDATES"
                      for target in node.targets))
    preset = "full_fa3_m16" if backend == "full_fa3" and blocks == (8, 16) else backend
    if backend == "full_fa3" and blocks == (8,):
        preset = "full_fa3_m8"
    fused_finalize = next(ast.literal_eval(node.value) for node in tree.body
                         if isinstance(node, ast.Assign) and any(
                             isinstance(target, ast.Name) and target.id == "SMALL_EXPERT_FINALIZE"
                             for target in node.targets))
    if fused_finalize:
        preset += "_finalize"
    direct_single = next(ast.literal_eval(node.value) for node in tree.body
                         if isinstance(node, ast.Assign) and any(
                             isinstance(target, ast.Name) and target.id == "DIRECT_SINGLE_EXPERTS"
                             for target in node.targets))
    if direct_single:
        preset = "single_nvfp4"
    return {
        "problem": "muse_decode_layer",
        "preset": preset,
        "expert_block_size_candidates": blocks,
        "small_expert_finalize": fused_finalize,
        "direct_single_experts": direct_single,
        "submission_sha256": hashlib.sha256(source.encode()).hexdigest(),
        "sources": {name: hashlib.sha256((ROOT / name).read_bytes()).hexdigest()
                    for name in SOURCES},
        "validation": "Build/syntax only; no claim of GPU compilation, correctness, or speed.",
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--preset", choices=PRESETS, default="full_fa3_m16_finalize")
    parser.add_argument("--output", type=Path, default=ROOT / "submission.py")
    parser.add_argument("--manifest", type=Path, help="optional source hashes for a frozen experiment")
    parser.add_argument("--check", action="store_true", help="fail if output is missing or stale")
    args = parser.parse_args()
    source = build_source(args.preset)
    if args.check:
        if not args.output.exists() or args.output.read_text() != source:
            parser.exit(1, f"Stale build: {args.output}; run python -m tools.build\n")
        print(f"Up to date: {args.output}")
        return
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(source)
    if args.manifest:
        args.manifest.parent.mkdir(parents=True, exist_ok=True)
        args.manifest.write_text(json.dumps(source_manifest(source), indent=2) + "\n")
    print(f"Built: {args.output}")


if __name__ == "__main__":
    main()
