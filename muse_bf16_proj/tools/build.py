"""Build a standalone OKC file: python -m tools.build --preset pdl."""

import argparse
import ast
from pathlib import Path

from projection.configs import CONFIGS

ROOT = Path(__file__).resolve().parents[1]
SOURCES = (
    "projection/shapes.py", "projection/configs.py",
    "projection/kernels/gemv.py", "projection/kernels/gemm.py",
    "projection/kernels/layout.py",
    "projection/kernels/reduce.py", "projection/kernels/tma.py",
    "projection/kernels/hopper_ws.py", "projection/kernels/router_cluster.py",
    "projection/kernels/hopper_overlap.py",
    "projection/kernels/early.py",
    "projection/runtime.py",
)


def build_source(preset="pdl"):
    if preset not in CONFIGS:
        raise ValueError(f"unknown preset: {preset}")
    chunks = ['# okc: problem=muse_bf16_proj\n',
              '# Generated by python -m tools.build; edit projection/ sources.\n']
    seen_imports = set()
    for name in SOURCES:
        source = (ROOT / name).read_text()
        lines = source.splitlines(keepends=True)
        chunks.append(f"\n# Source: {name}\n")
        for node in ast.parse(source).body:
            if isinstance(node, ast.ImportFrom) and node.level:
                continue
            if isinstance(node, ast.Expr) and isinstance(node.value, ast.Constant) and isinstance(node.value.value, str):
                continue
            if isinstance(node, (ast.Import, ast.ImportFrom)):
                key = ast.dump(node)
                if key in seen_imports:
                    continue
                seen_imports.add(key)
            start = min([node.lineno] + [d.lineno for d in getattr(node, "decorator_list", [])])
            block = ''.join(lines[start - 1:node.end_lineno])
            if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == "PRESET" for t in node.targets):
                block = f"PRESET = {preset!r}\n"
            chunks.append(block + '\n\n')
    result = ''.join(chunks).rstrip() + '\n'
    ast.parse(result)
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--preset", choices=tuple(CONFIGS), default="pdl")
    parser.add_argument("--output", type=Path, default=ROOT / "submission.py")
    parser.add_argument("--check", action="store_true", help="fail if output is missing or stale")
    args = parser.parse_args()
    source = build_source(args.preset)
    if args.check:
        if not args.output.exists() or args.output.read_text() != source:
            raise SystemExit(f"Stale build: {args.output}; run python -m tools.build --preset {args.preset}")
        print(f"Up to date: {args.output}")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(source)
        print(f"Built {args.preset}: {args.output}")


if __name__ == "__main__":
    main()
